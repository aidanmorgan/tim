    private static string TargetHash(System.Xml.Linq.XElement target) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(target.ToString(System.Xml.Linq.SaveOptions.DisableFormatting))));

    [Fact]
    public void RepositoryMsBuildLogicIsOnlyThePinnedTargetsAndImports()
    {
        var violations = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var path in Files.Where(path => path.EndsWith(".csproj", StringComparison.Ordinal) || path.EndsWith(".props", StringComparison.Ordinal) ||
                     path.EndsWith(".targets", StringComparison.Ordinal)).Where(path => !IsVendored(path)).Order(StringComparer.Ordinal))
        {
            var document = System.Xml.Linq.XDocument.Parse(Read(path));
            foreach (var element in document.Descendants().Where(element => BuildLogicElements.Contains(element.Name.LocalName, StringComparer.Ordinal)))
            {
                var inPinnedTarget = element.Ancestors().Any(ancestor => ancestor.Name.LocalName == "Target" &&
                    PinnedTargets.ContainsKey($"{path}:{(string?)ancestor.Attribute("Name")}"));
                switch (element.Name.LocalName)
                {
                    case "Target":
                        var key = $"{path}:{(string?)element.Attribute("Name")}";
                        seen.Add(key);
                        if (!PinnedTargets.TryGetValue(key, out var pinned)) violations.Add($"{key}: unpinned target (hash {TargetHash(element)})");
                        else if (pinned != TargetHash(element)) violations.Add($"{key}: target changed (hash {TargetHash(element)}, pinned {pinned})");
                        break;
                    case "Import":
                        var project = (string?)element.Attribute("Project") ?? "";
                        var rootImport = Path.GetFileName(path) is "Directory.Build.props" or "Directory.Build.targets" && path.Contains('/', StringComparison.Ordinal) &&
                            project.Contains($"GetPathOfFileAbove('{Path.GetFileName(path)}'", StringComparison.Ordinal);
                        if (!rootImport && !PinnedImports.GetValueOrDefault(path, []).Contains(project, StringComparer.Ordinal))
                            violations.Add($"{path}: unpinned import {project}");
                        break;
                    default:
                        if (!inPinnedTarget) violations.Add($"{path}: <{element.Name.LocalName}> outside a pinned target");
                        break;
                }
            }
        }
        foreach (var missing in PinnedTargets.Keys.Where(key => !seen.Contains(key))) violations.Add($"{missing}: pinned target missing");
        AssertNone(violations);
    }

