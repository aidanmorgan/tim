    /// <summary>One Csc task run in a gate build's binary log: the project, the compiler command line (as tokens) and
    /// the Sources items the task received.</summary>
    private sealed record CscRun(string Binlog, string Project, string[] Arguments, string[] Sources)
    {
        public string ProjectDirectory => Path.GetDirectoryName(Project) ?? "";
        public string ProjectName => Path.GetFileNameWithoutExtension(Project);
        /// <summary>The compile's intermediate directory: where its /out: assembly is written.</summary>
        public string IntermediateDirectory => Path.GetDirectoryName(Path.GetFullPath(Path.Combine(ProjectDirectory,
            Values("out").Single()))) ?? "";
        /// <summary>The values of one switch (/name: or -name:, case-insensitive), in order.</summary>
        public IEnumerable<string> Values(string name) => Arguments
            .Where(argument => argument.Length > name.Length + 1 && (argument[0] is '/' or '-') &&
                argument.AsSpan(1, name.Length).Equals(name, StringComparison.OrdinalIgnoreCase) && argument[name.Length + 1] == ':')
            .Select(argument => argument[(name.Length + 2)..]);
        /// <summary>Every form of one switch (/name, /name+, /name-, /name:value), case-insensitive.</summary>
        public IEnumerable<string> Forms(string name) => Arguments
            .Where(argument => argument.Length > name.Length && (argument[0] is '/' or '-') &&
                argument.AsSpan(1, name.Length).Equals(name, StringComparison.OrdinalIgnoreCase) &&
                (argument.Length == name.Length + 1 || argument[name.Length + 1] is ':' or '+' or '-'));
        public string Resolve(string path) => Path.GetFullPath(Path.Combine(ProjectDirectory, path));
    }

    private static readonly Lazy<List<CscRun>> CscRuns = new(() =>
        Directory.EnumerateFiles(BinlogDirectory, "*.binlog").Order(StringComparer.Ordinal).SelectMany(ReplayCscRuns).ToList());

    // Shared semantic seam: use the same real Csc sources, references, defines and options as the static gate.
    internal static IEnumerable<CSharpCompilation> MatchingCompilations()
    {
        foreach (var run in CscRuns.Value)
        {
            var arguments = CSharpCommandLineParser.Default.Parse(run.Arguments, run.ProjectDirectory, sdkDirectory: null);
            var trees = run.Sources.Select(path => run.Resolve(path)).Distinct(StringComparer.Ordinal)
                .Select(path => CSharpSyntaxTree.ParseText(File.ReadAllText(path), arguments.ParseOptions, path));
            var references = arguments.MetadataReferences.Select(reference =>
                MetadataReference.CreateFromFile(run.Resolve(reference.Reference), reference.Properties));
            yield return CSharpCompilation.Create(run.ProjectName, trees, references, arguments.CompilationOptions);
        }
    }

    private static string[] CommandLineTokens(string commandLine)
    {
        var tokens = new List<string>();
        var current = new StringBuilder();
        var quoted = false;
        foreach (var character in commandLine)
        {
            if (character == '"') { quoted = !quoted; continue; }
            if (char.IsWhiteSpace(character) && !quoted)
            {
                if (current.Length > 0) { tokens.Add(current.ToString()); current.Clear(); }
                continue;
            }
            current.Append(character);
        }
        if (current.Length > 0) tokens.Add(current.ToString());
        return tokens.ToArray();
    }

    private static List<CscRun> ReplayCscRuns(string binlog)
    {
        var runs = new List<CscRun>();
        var commandLines = new Dictionary<(int, int, int), (string Project, string CommandLine)>();
        var sources = new Dictionary<(int, int, int), string[]>();
        var replay = new Microsoft.Build.Logging.BinaryLogReplayEventSource();
        replay.AnyEventRaised += (_, raised) =>
        {
            if (raised.BuildEventContext is not { } context) return;
            var key = (context.NodeId, context.ProjectContextId, context.TaskId);
            if (raised is Microsoft.Build.Framework.TaskCommandLineEventArgs { TaskName: "Csc" } command)
                commandLines[key] = (command.ProjectFile ?? "", command.CommandLine);
            else if (raised is Microsoft.Build.Framework.TaskParameterEventArgs { ItemType: "Sources" } parameter &&
                     parameter.Kind == Microsoft.Build.Framework.TaskParameterMessageKind.TaskInput)
                sources[key] = parameter.Items.Cast<Microsoft.Build.Framework.ITaskItem>().Select(item => item.ItemSpec).ToArray();
        };
        replay.Replay(binlog);
        foreach (var (key, (project, commandLine)) in commandLines)
        {
            var directory = Path.GetDirectoryName(project) ?? "";
            var compiled = sources.GetValueOrDefault(key, []).Select(spec => Path.GetFullPath(Path.Combine(directory, spec))).ToArray();
            runs.Add(new(binlog, project, CommandLineTokens(commandLine), compiled));
        }
        return runs;
    }

    private sealed record CompileInputs(Dictionary<string, HashSet<string>> ByProject, List<string> Problems);

    private static readonly Lazy<CompileInputs> Compiled = new(ReadCompileInputs);

    /// <summary>Each compile's sources (full paths), keyed by repository-relative project. In the gate, the union of the
    /// Sources every logged Csc run of that project received; every expected compile must have run and every run must be
    /// an expected compile. No evaluated-source alternative is accepted.</summary>
    private static CompileInputs ReadCompileInputs()
    {
        var byProject = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        var problems = new List<string>();
        foreach (var run in CscRuns.Value)
        {
            var project = InRepository(run.Project) ? Relative(run.Project) : run.Project;
            if (!ExpectedCompiles.Contains(project, StringComparer.Ordinal) && project != VendoredProject)
                problems.Add($"{Path.GetFileName(run.Binlog)}: Csc compiled {project}, which is no expected compile");
            if (!byProject.TryGetValue(project, out var sources)) byProject[project] = sources = new(StringComparer.Ordinal);
            sources.UnionWith(run.Sources);
        }
        foreach (var expected in ExpectedCompiles.Where(expected => !byProject.ContainsKey(expected)))
            problems.Add($"{expected}: no Csc run in the gate builds' binary logs (every compile must be logged)");
        // Every gate build's log, each with its own compiles (the PLAYTEST build with its define).
        foreach (var (log, compiles) in ExpectedLogCompiles)
        {
            var runs = CscRuns.Value.Where(run => Path.GetFileName(run.Binlog) == log).ToArray();
            if (runs.Length == 0) problems.Add($"{log}: missing (every gate build's binary log is required)");
            foreach (var expected in compiles.Where(expected => !runs.Any(run => Relative(run.Project) == expected)))
                problems.Add($"{log}: no Csc run of {expected}");
        }
        foreach (var run in CscRuns.Value.Where(run => Path.GetFileName(run.Binlog) == "playtest.binlog" &&
                     PlaytestProjects.Contains(Relative(run.Project), StringComparer.Ordinal) &&
                     !run.Values("define").Any(value => value.Split(';').Contains("PLAYTEST", StringComparer.Ordinal))))
            problems.Add($"playtest.binlog: {Relative(run.Project)} compiled without the PLAYTEST define");
        return new(byProject, problems);
    }

