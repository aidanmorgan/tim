    // Roslyn treats these file names as generated code and skips analyzers on them.
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];
    // Identifiers that suppress or hide diagnostics however they are spelled at the use site (an alias, a qualified
    // name or an attribute suffix all contain one of these tokens).
    private static readonly string[] SuppressionIdentifiers =
    [
        "SuppressMessage", "SuppressMessageAttribute", "UnconditionalSuppressMessage", "UnconditionalSuppressMessageAttribute",
        "GeneratedCode", "GeneratedCodeAttribute",
    ];
    // The same markers in raw text, for code in an #if branch no parse activates.
    private static readonly Regex DisabledMarker = new(
        @"#\s*pragma\s+warning|#\s*nullable\b|#\s*line\b|\b(Unconditional)?SuppressMessage|\bGeneratedCode|<\s*auto-?generated|" +
        @"\bcatch\s*(\([^)]*\))?\s*(when\s*\([^)]*\))?\s*\{\s*(;\s*)*\}", RegexOptions.IgnoreCase);

    /// <summary>Two parses cover every branch the preprocessor can take: no symbols, and every symbol the file tests
    /// (#if DEBUG, PLAYTEST, ...). What is still inactive in a parse is scanned as raw text.</summary>
    private static IEnumerable<SyntaxNode> Parses(string text)
    {
        var symbols = Regex.Matches(text, @"^\s*#\s*(?:if|elif)\b(.*)$", RegexOptions.Multiline)
            .SelectMany(match => Regex.Matches(match.Groups[1].Value, "[A-Za-z_][A-Za-z0-9_]*").Select(name => name.Value))
            .Where(name => name is not ("true" or "false" or "defined")).Append("DEBUG").Distinct(StringComparer.Ordinal).ToArray();
        var options = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview);
        yield return CSharpSyntaxTree.ParseText(text, options).GetRoot();
        yield return CSharpSyntaxTree.ParseText(text, options.WithPreprocessorSymbols(symbols)).GetRoot();
    }

    private static int LineOf(SyntaxNode node) => node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
    private static int LineOf(SyntaxTrivia trivia) => trivia.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
    private static int LineOf(SyntaxToken token) => token.GetLocation().GetLineSpan().StartLinePosition.Line + 1;

