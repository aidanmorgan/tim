    private static readonly string Root = FindRoot();

    private static string FindRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
            if (File.Exists(Path.Combine(directory.FullName, "CuriousContraptions.slnx"))) return directory.FullName;
        throw new InvalidOperationException("The repository root (CuriousContraptions.slnx) is not above the test output.");
    }

    // Build outputs, never repository inputs.
    private static readonly string[] OutputDirectoryNames = ["bin", "obj", ".godot", "node_modules", "AppBundle", "TestResults"];

    /// <summary>Every repository file: in a git checkout, tracked plus untracked-but-not-ignored files; in the hook's
    /// index snapshot (no .git), every file except build outputs and nested repositories.</summary>
    private static readonly IReadOnlyList<string> Files = RepositoryFiles();

    internal static string[] RepositoryFiles()
    {
        if (!File.Exists(Path.Combine(Root, ".git")) && !Directory.Exists(Path.Combine(Root, ".git"))) return Walk(Root).ToArray();
        var listed = Run("git", ["-C", Root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"]);
        return listed.Split('\0', StringSplitOptions.RemoveEmptyEntries).Where(path => File.Exists(Path.Combine(Root, path))).Distinct().ToArray();
    }

    private static IEnumerable<string> Walk(string directory)
    {
        foreach (var file in Directory.EnumerateFiles(directory))
            yield return Path.GetRelativePath(Root, file).Replace('\\', '/');
        foreach (var child in Directory.EnumerateDirectories(directory))
        {
            if (OutputDirectoryNames.Contains(Path.GetFileName(child), StringComparer.Ordinal) || Path.GetFileName(child) == ".git") continue;
            if (File.Exists(Path.Combine(child, ".git")) || Directory.Exists(Path.Combine(child, ".git"))) continue;
            foreach (var file in Walk(child)) yield return file;
        }
    }

    private static string Run(string program, string[] arguments)
    {
        var start = new ProcessStartInfo(program) { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
        foreach (var argument in arguments) start.ArgumentList.Add(argument);
        using var process = Process.Start(start) ?? throw new InvalidOperationException($"Could not start {program}.");
        var output = process.StandardOutput.ReadToEnd();
        var errors = process.StandardError.ReadToEnd();
        process.WaitForExit();
        if (process.ExitCode != 0) throw new InvalidOperationException($"{program} {string.Join(' ', arguments)} failed: {errors}");
        return output;
    }

