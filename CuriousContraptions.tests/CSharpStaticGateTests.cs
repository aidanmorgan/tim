                        foreach (Match marker in DisabledMarker.Matches(trivia.ToString()))
                            violations.Add($"{shown}:{LineOf(trivia)}: in an inactive #if branch: {marker.Value.Trim()}");
                }
                foreach (var token in root.DescendantTokens(descendIntoTrivia: true))
                    if (token.IsKind(SyntaxKind.IdentifierToken) && SuppressionIdentifiers.Contains(token.ValueText, StringComparer.Ordinal))
