    private static List<string> SuppressionMarkers(string source) =>
        Parses(source).SelectMany(root => root.DescendantTokens(descendIntoTrivia: true)
                .Where(token => token.IsKind(SyntaxKind.IdentifierToken) && SuppressionIdentifiers.Contains(token.ValueText, StringComparer.Ordinal))
                .Select(token => token.ValueText)
            .Concat(root.DescendantTrivia(descendIntoTrivia: true).Where(trivia => trivia.IsKind(SyntaxKind.DisabledTextTrivia))
                .SelectMany(trivia => DisabledMarker.Matches(trivia.ToString()).Select(match => match.Value.Trim())))
            .Concat(root.DescendantTrivia(descendIntoTrivia: true).Where(trivia => trivia.GetStructure() is PragmaWarningDirectiveTriviaSyntax)
                .Select(trivia => "#pragma"))
            .Concat(root.DescendantTrivia(descendIntoTrivia: true)
                .Where(trivia => trivia.GetStructure() is LineDirectiveTriviaSyntax or LineSpanDirectiveTriviaSyntax)
                .Select(trivia => "#line")))
            .Distinct().ToList();

