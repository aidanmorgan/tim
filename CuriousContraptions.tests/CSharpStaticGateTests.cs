    /// <summary>One logged compile's violations of the pinned compiler inputs.</summary>
    private static IEnumerable<string> CompilerInputViolations(CscRun run)
    {
        var project = InRepository(run.Project) ? Relative(run.Project) : run.Project;
        var where = $"{Path.GetFileName(run.Binlog)}: {project}";
        if (run.Arguments.Length == 0 || !SdkCompiler.IsMatch(run.Arguments[0])) yield return $"{where}: compiler {run.Arguments.FirstOrDefault()} is not the SDK's csc";
        if (!run.Forms("noconfig").Any()) yield return $"{where}: no /noconfig";
        foreach (var file in run.Arguments.Where(argument => argument.StartsWith('@'))) yield return $"{where}: response file {file}";
        // Warnings as errors: /warnaserror+ and exactly one list of exactly the pinned codes; no other form (no exemption).
        var warnAsError = run.Forms("warnaserror").ToArray();
        if (!warnAsError.Contains("/warnaserror+", StringComparer.Ordinal)) yield return $"{where}: compiled without /warnaserror+";
        var lists = warnAsError.Where(form => form.StartsWith("/warnaserror+:", StringComparison.Ordinal)).ToArray();
        var listed = Codes(lists.Select(form => form["/warnaserror+:".Length..]));
        if (lists.Length != 1 || !listed.SequenceEqual(Codes(PinnedWarningsAsErrors), StringComparer.Ordinal))
            yield return $"{where}: /warnaserror+: lists {string.Join(',', listed)} in {lists.Length} form(s), not exactly the pinned {string.Join(',', Codes(PinnedWarningsAsErrors))}";
        foreach (var form in warnAsError.Where(form => form != "/warnaserror+" && !lists.Contains(form, StringComparer.Ordinal)))
            yield return $"{where}: {form}";
        foreach (var code in Codes(run.Values("nowarn")).Where(code => !PinnedNoWarn.Contains(code, StringComparer.Ordinal)))
            yield return $"{where}: /nowarn:{code}";
        var warn = run.Values("warn").Concat(run.Values("w")).ToArray();
        if (warn is not ["10"]) yield return $"{where}: /warn:{string.Join(',', warn)} (must be exactly 10)";
        var nullable = run.Values("nullable").ToArray();
        if (nullable is not ["enable"]) yield return $"{where}: /nullable:{string.Join(',', nullable)} (must be exactly enable)";
        // Every token is one of the compile's sources or a pinned switch; the diagnostic switches' values are pinned.
        var sources = run.Sources.ToHashSet(StringComparer.Ordinal);
        foreach (var token in run.Arguments.Skip(1).Where(token => !sources.Contains(run.Resolve(token))))
        {
            var name = Regex.Match(token, "^[/-]([A-Za-z0-9]+)").Groups[1].Value;
            if (!AllowedSwitches.Contains(name, StringComparer.Ordinal)) yield return $"{where}: unpinned compiler argument {token}";
        }
        foreach (var (name, values) in PinnedSwitchValues)
            foreach (var value in run.Values(name).Where(value => !values.Contains(value, StringComparer.Ordinal)))
                yield return $"{where}: /{name}:{value} (unpinned value)";
        // Analyzers: the four .NET analyzer and code-style assemblies, and only pinned assemblies from the SDK, or from
        // their pinned NuGet package.
        var analyzers = run.Values("analyzer").Select(run.Resolve).ToArray();
        foreach (var analyzer in analyzers)
        {
            var file = Path.GetFileName(analyzer);
            var package = IsUnder(analyzer, NuGetRoot) ? Path.GetRelativePath(NuGetRoot, analyzer).Split(['/', '\\'])[0] : "";
            var pinned = IsUnder(analyzer, DotnetRoot) ? SdkAnalyzers.Contains(file, StringComparer.Ordinal)
                : PackageAnalyzers.Any(entry => entry.Package == package && entry.File == file && entry.Projects.Contains(project, StringComparer.Ordinal)) ||
                  (IsUnder(analyzer, NuGetRoot) && IsPinnedRefPackAnalyzer(analyzer, project));
            if (!pinned) yield return $"{where}: unpinned analyzer {analyzer} (package {package}, project {project})";
        }
        foreach (var required in RequiredAnalyzers.Where(required => !analyzers.Any(analyzer => Path.GetFileName(analyzer) == required)))
            yield return $"{where}: compiled without {required}";
        // Analyzer configuration: the root .editorconfig, the SDK's analysis level, and the compile's own generated files.
        var configs = run.Values("analyzerconfig").Select(run.Resolve).ToArray();
        var rootConfig = Path.Combine(Root, ".editorconfig");
        if (!configs.Contains(rootConfig, StringComparer.Ordinal)) yield return $"{where}: compiled without the root .editorconfig";
        if (!configs.Any(config => Path.GetFileName(config) == AnalysisLevelConfig && IsUnder(config, DotnetRoot)))
            yield return $"{where}: compiled without the SDK's {AnalysisLevelConfig}";
        foreach (var config in configs)
        {
            var name = Path.GetFileName(config);
            var own = Path.GetDirectoryName(config) == run.IntermediateDirectory;
            if (config == rootConfig || (name == AnalysisLevelConfig && IsUnder(config, DotnetRoot))) continue;
            // An .editorconfig above the repository is inert: the root one says root = true.
            if (name == ".editorconfig" && !InRepository(config) && IsUnder(Root, Path.GetDirectoryName(config)!)) continue;
            if (own && name == run.ProjectName + ".GeneratedMSBuildEditorConfig.editorconfig")
            {
                foreach (var line in GeneratedConfigViolations(config, project)) yield return $"{where}: {Display(config)}: {line}";
                continue;
            }
            if (own && name == run.ProjectName + ".PackageSources.globalconfig")
            {
                foreach (var line in PackageConfigViolations(config)) yield return $"{where}: {Display(config)}: {line}";
                continue;
            }
            yield return $"{where}: unpinned analyzer configuration {config}";
        }
    }

    // The generated MSBuild config carries only the pinned build properties (analyzers read them), with the analyzer
    // switches at their pinned values; no item metadata.
    private static IEnumerable<string> GeneratedConfigViolations(string config, string project)
    {
        var present = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in File.ReadAllLines(config).Select(line => line.Trim()).Where(line => line.Length > 0 && !line.StartsWith('#')))
        {
            if (line == "is_global = true") continue;
            var property = Regex.Match(line, @"^build_property\.([A-Za-z0-9_]+) =(.*)$");
            if (!property.Success || !GeneratedConfigKeys.Contains(property.Groups[1].Value, StringComparer.Ordinal))
            {
                yield return line;
                continue;
            }
            present[property.Groups[1].Value] = property.Groups[2].Value.Trim();
        }
        foreach (var (key, value) in PinnedGeneratedValues)
            if (present.TryGetValue(key, out var actual) && actual != value) yield return $"build_property.{key} = {actual} (pinned {value})";
        foreach (var (key, required) in RequiredAnalyzerSwitches)
        {
            var value = present.GetValueOrDefault(key, "");
            if (value is not ("" or "true")) yield return $"build_property.{key} = {value} (only true or unset)";
            if (required.Contains(project, StringComparer.Ordinal) && value != "true") yield return $"build_property.{key} = {value} (must be true here)";
        }
    }

