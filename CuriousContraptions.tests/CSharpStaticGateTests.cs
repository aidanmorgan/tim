                violations.Add($"{shown}: generated-code file name");
            var generatedWire = generated || (InRepository(path) && Relative(path) == GeneratedWire);
            foreach (var root in Parses(File.ReadAllText(path)))
            {
                foreach (var trivia in root.DescendantTrivia(descendIntoTrivia: true))
