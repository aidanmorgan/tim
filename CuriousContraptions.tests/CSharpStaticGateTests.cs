    private static readonly string[] ArgumentExceptionNames =
        ["ArgumentException", "System.ArgumentException", "global::System.ArgumentException"];

    // The ArgumentException names in one file: every qualification, plus any using alias for it.
    private static string[] ArgumentExceptionNamesIn(SyntaxNode root) => ArgumentExceptionNames.Concat(root.DescendantNodes()
            .OfType<UsingDirectiveSyntax>().Where(directive => directive.Alias is not null && directive.Name is not null &&
                (ArgumentExceptionNames.Contains(directive.Name.ToString(), StringComparer.Ordinal) ||
                 directive.Name.ToString().EndsWith(".ArgumentException", StringComparison.Ordinal)))
            .Select(directive => directive.Alias!.Name.Identifier.ValueText)).ToArray();

    // Any creation of an ArgumentException: by name in any qualification or alias, target-typed into a declared
    // ArgumentException, or through ArgumentException.ThrowIf*.
    private static IEnumerable<(int Line, string Text)> ArgumentExceptionCreations(SyntaxNode body, string[] names)
    {
        foreach (var node in body.DescendantNodes())
        {
            var created = node switch
            {
                ObjectCreationExpressionSyntax creation => names.Contains(creation.Type.ToString(), StringComparer.Ordinal),
                ImplicitObjectCreationExpressionSyntax implicitCreation => implicitCreation.Parent?.Parent?.Parent is VariableDeclarationSyntax declaration &&
                    names.Contains(declaration.Type.ToString(), StringComparer.Ordinal),
                InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax access } =>
                    names.Contains(access.Expression.ToString(), StringComparer.Ordinal) &&
                    access.Name.Identifier.ValueText.StartsWith("ThrowIf", StringComparison.Ordinal),
                _ => false,
            };
            if (created) yield return (LineOf(node), node.ToString());
        }
    }

    private sealed record DeclaredMethod(string Path, string Type, MethodDeclarationSyntax Method, string[] ArgumentExceptionNames);

    /// <summary>Every method declared in the repository's C# files, by declaring type (partial types merge).</summary>
    private static readonly Lazy<ILookup<string, DeclaredMethod>> RepositoryMethods = new(() => Files
        .Where(path => path.EndsWith(".cs", StringComparison.Ordinal) && !IsVendored(path))
        .SelectMany(path =>
        {
            var root = CSharpSyntaxTree.ParseText(Read(path)).GetRoot();
            var names = ArgumentExceptionNamesIn(root);
            return root.DescendantNodes().OfType<MethodDeclarationSyntax>()
                .Where(method => method.Parent is TypeDeclarationSyntax)
                .Select(method => new DeclaredMethod(path, ((TypeDeclarationSyntax)method.Parent!).Identifier.ValueText, method, names));
        }).ToLookup(method => method.Type, StringComparer.Ordinal));

    // A throw helper: a method whose whole body is a throw, or that is marked [DoesNotReturn].
    private static bool IsThrowHelper(MethodDeclarationSyntax method) =>
        method.AttributeLists.SelectMany(list => list.Attributes).Any(attribute => attribute.Name.ToString() is "DoesNotReturn" or "System.Diagnostics.CodeAnalysis.DoesNotReturn") ||
        method.ExpressionBody?.Expression is ThrowExpressionSyntax ||
        method.Body is { Statements: [ThrowStatementSyntax] };

    /// <summary>A pinned method and what it calls: methods of its own type (by name, through this. or Type.), followed
    /// transitively, and throw helpers of any repository type.</summary>
    private static List<DeclaredMethod> ReachableMethods(DeclaredMethod start, ILookup<string, DeclaredMethod> methods)
    {
        var reached = new List<DeclaredMethod>();
        var visited = new HashSet<MethodDeclarationSyntax>();
        var pending = new Stack<DeclaredMethod>([start]);
        while (pending.TryPop(out var current))
        {
            if (!visited.Add(current.Method)) continue;
            reached.Add(current);
            foreach (var invocation in current.Method.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                var (owner, name) = invocation.Expression switch
                {
                    IdentifierNameSyntax identifier => (current.Type, identifier.Identifier.ValueText),
                    MemberAccessExpressionSyntax { Expression: ThisExpressionSyntax } access => (current.Type, access.Name.Identifier.ValueText),
                    MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax type } access => (type.Identifier.ValueText, access.Name.Identifier.ValueText),
                    _ => ("", ""),
                };
                foreach (var callee in methods[owner].Where(method => method.Method.Identifier.ValueText == name))
                    if (owner == current.Type || IsThrowHelper(callee.Method)) pending.Push(callee);
            }
        }
        return reached;
    }

