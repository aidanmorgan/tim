    private sealed record CatchSite(string Path, int Line, string Container, CatchKind Kind);
    public enum CatchKind { Handled, Empty, CatchAll }

    private static readonly Lazy<List<CatchSite>> Catches = new(() =>
    {
        var sites = new HashSet<CatchSite>();
        foreach (var path in SourcesToScan().Where(path => !(InRepository(path) && Relative(path) == GeneratedWire)))
            foreach (var root in Parses(File.ReadAllText(path)))
                foreach (var clause in root.DescendantNodes().OfType<CatchClauseSyntax>())
                {
                    var kind = Kind(clause);
                    if (kind != CatchKind.Handled) sites.Add(new(Display(path), LineOf(clause), Container(clause), kind));
                }
        return sites.OrderBy(site => site.Path, StringComparer.Ordinal).ThenBy(site => site.Line).ToList();
    });

    private static CatchKind Kind(CatchClauseSyntax clause) =>
        IsEmpty(clause) ? CatchKind.Empty : IsCatchAll(clause) && !Rethrows(clause) && !NarrowsByType(clause) ? CatchKind.CatchAll : CatchKind.Handled;

    // No statement, or only empty statements (`catch { ; }`), handles nothing.
    private static bool IsEmpty(CatchClauseSyntax clause) => clause.Block.Statements.All(statement => statement is EmptyStatementSyntax);

    private static readonly string[] GeneralTypes = ["Exception", "System.Exception", "global::System.Exception", "SystemException", "System.SystemException"];
    private static bool IsGeneral(TypeSyntax type) => GeneralTypes.Contains(type.ToString(), StringComparer.Ordinal);
    private static bool IsCatchAll(CatchClauseSyntax clause) => clause.Declaration is null || IsGeneral(clause.Declaration.Type);
    // Ends by rethrowing (`throw;`) or by throwing a new exception that carries the caught one as an argument.
    private static bool Rethrows(CatchClauseSyntax clause) => clause.Block.Statements.Last() switch
    {
        ThrowStatementSyntax { Expression: null } => true,
        ThrowStatementSyntax { Expression: BaseObjectCreationExpressionSyntax { ArgumentList: { } arguments } } =>
            clause.Declaration?.Identifier.ValueText is { Length: > 0 } caught &&
            arguments.Arguments.Any(argument => argument.Expression is IdentifierNameSyntax name && name.Identifier.ValueText == caught),
        _ => false
    };

    // `when (error is A)` or `when (error is A or B)` with only specific types is a typed catch; any other filter keeps
    // it a catch-all. In `is A or B` the parser yields type or constant patterns for the names.
    private static bool NarrowsByType(CatchClauseSyntax clause)
    {
        var caught = clause.Declaration?.Identifier.ValueText;
        if (string.IsNullOrEmpty(caught)) return false;
        return clause.Filter?.FilterExpression switch
        {
            BinaryExpressionSyntax { RawKind: (int)SyntaxKind.IsExpression, Left: IdentifierNameSyntax name, Right: TypeSyntax type }
                => name.Identifier.ValueText == caught && !IsGeneral(type),
            IsPatternExpressionSyntax { Expression: IdentifierNameSyntax name } test => name.Identifier.ValueText == caught && SpecificTypes(test.Pattern),
            _ => false
        };
    }

    private static bool SpecificTypes(PatternSyntax pattern) => pattern switch
    {
        TypePatternSyntax type => !IsGeneral(type.Type),
        ConstantPatternSyntax { Expression: NameSyntax or MemberAccessExpressionSyntax } name => !GeneralTypes.Contains(name.Expression.ToString(), StringComparer.Ordinal),
        BinaryPatternSyntax { OperatorToken.ValueText: "or" } either => SpecificTypes(either.Left) && SpecificTypes(either.Right),
        ParenthesizedPatternSyntax inner => SpecificTypes(inner.Pattern),
        _ => false
    };

    // Lambdas and local functions are their own containers, so no exemption reaches code nested inside a method.
    private static string Container(SyntaxNode node)
    {
        var names = new List<string>();
        for (var current = node.Parent; current is not null; current = current.Parent)
            switch (current)
            {
                case AnonymousFunctionExpressionSyntax: return "<lambda>";
                case LocalFunctionStatementSyntax local: return "<local function " + local.Identifier.ValueText + ">";
                case MethodDeclarationSyntax method: names.Add(method.Identifier.ValueText); break;
                case ConstructorDeclarationSyntax: names.Add(".ctor"); break;
                case AccessorDeclarationSyntax accessor: names.Add(accessor.Keyword.ValueText); break;
                case PropertyDeclarationSyntax property: names.Add(property.Identifier.ValueText); break;
                case BaseTypeDeclarationSyntax type: names.Add(type.Identifier.ValueText); break;
            }
        names.Reverse();
        return names.Count == 0 ? "<top-level>" : string.Join('.', names);
    }

