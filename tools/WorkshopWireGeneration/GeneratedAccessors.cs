namespace CuriousContraptions.WorkshopWireGeneration;

/// <summary>Joins pinned flatc output with the one supported nullable ArraySegment accessor surface.</summary>
public static class GeneratedAccessors
{
    public static void Write(string directory, string output)
    {
        var files = Directory.GetFiles(directory, "*.cs").Order(StringComparer.Ordinal).ToArray();
        if (files.Length == 0) throw new ArgumentException("No generated types.");
        var joined = Join(files.Select(File.ReadAllText));
        File.WriteAllText(output, joined);
    }

    public static string Join(IEnumerable<string> files)
    {
        var bodies = files.Select(Body).ToArray();
        var joined = string.Join("\n\n", bodies);
        if (!joined.Contains("FLATBUFFERS_25_2_10", StringComparison.Ordinal) ||
            joined.Replace("FLATBUFFERS_25_2_10", "", StringComparison.Ordinal).Contains("FLATBUFFERS_", StringComparison.Ordinal))
            throw new ArgumentException("Expected pinned flatc 25.2.10 runtime stamp.");
        return "// <auto-generated>\n//  automatically generated by the FlatBuffers compiler, do not modify\n// </auto-generated>\n\n" +
            "namespace CuriousContraptions.Wire\n{\nusing global::System;\nusing global::System.Collections.Generic;\nusing global::Google.FlatBuffers;\n" +
            joined + "\n\n}\n";
    }

    private static string Body(string input)
    {
        var lines = SelectAccessors(input).Split('\n');
        var opening = Array.FindIndex(lines, line => line.Trim() == "{");
        var closing = Array.FindLastIndex(lines, line => line.Trim() == "}");
        if (opening < 0 || closing <= opening ||
            !lines.Take(opening).Any(line => line.Trim() == "namespace CuriousContraptions.Wire"))
            throw new ArgumentException("Expected generated wire namespace.");
        var first = opening + 1;
        while (first < closing && (string.IsNullOrWhiteSpace(lines[first]) || lines[first].StartsWith("using ", StringComparison.Ordinal)))
            first++;
        return string.Join("\n", lines[first..closing]).TrimEnd();
    }

    public static string SelectAccessors(string input)
    {
        var result = new System.Text.StringBuilder();
        var branch = AccessorBranch.Outside;
        foreach (var line in input.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
        {
            var directive = line.Trim();
            if (directive.StartsWith('#'))
            {
                branch = (directive, branch) switch
                {
                    ("#if ENABLE_SPAN_T", AccessorBranch.Outside) => AccessorBranch.Span,
                    ("#else", AccessorBranch.Span) => AccessorBranch.ArraySegment,
                    ("#endif", AccessorBranch.ArraySegment) => AccessorBranch.Outside,
                    _ => throw new ArgumentException("Unexpected generated accessor directive.")
                };
            }
            else if (branch != AccessorBranch.Span) result.AppendLine(line);
        }
        if (branch != AccessorBranch.Outside) throw new ArgumentException("Unbalanced generated accessor directive.");
        return result.ToString();
    }

    private enum AccessorBranch { Outside, Span, ArraySegment }
}
